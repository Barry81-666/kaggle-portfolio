source("core.R")
started<-Sys.time();set.seed(814);checks<-list()
check<-function(name,condition) {
  if(!isTRUE(condition)) stop("FAILED: ",name)
  checks[[length(checks)+1]]<<-data.table(check=name,passed=TRUE)
}
check("verdict positive/negative/unknown",identical(verdict_map(c("YES","NO","UNK",NA)),c(1,0,NA_real_,NA_real_)))
check("unexpected verdict stops",inherits(try(verdict_map("MAYBE"),silent=TRUE),"try-error"))
x<-c(0,.05,.25,.5,.55,.9,.95,1,.75,NA)
check("documented any-affirmed codes",identical(yunus_map(x)$y,c(0,NA,1,NA,1,1,1,1,NA,NA)))
check("documented moderate codes",identical(yunus_map(x,TRUE)$y,c(0,NA,0,NA,1,1,1,1,NA,NA)))
check("undocumented codes stay missing",identical(which(yunus_map(x)$undocumented),9L))
check("numeric equality tolerance",yunus_map(.25+1e-9)$y==1 && is.na(yunus_map(.25+1e-6)$y))
check("fewer than three sources excludes LCM",identical(lcm_allowed(0:3),c(FALSE,FALSE,FALSE,TRUE)))
v<-vote(bin_patterns)
check("all 32 patterns partition",all(v$keep+v$g2_tie+v$group_disagree==1))
check("common-sample majority identity",all(v$major[v$keep]==v$common[v$keep]))
check("filter requires four matching votes",all(pmax(rowSums(bin_patterns),5-rowSums(bin_patterns))[v$keep]>=4))
check("AUC ties and direction",abs(auc_from_rank(rank(c(1,2,2,3)),c(0,0,1,1))-.875)<1e-12)
check("one-class AUC missing",is.na(auc_from_rank(1:3,rep(1,3))))
s<-as.list(fread("simulation-scenarios.csv")[1]);p<-(1:32)/sum(1:32);cal<-calibrate(p,s)
check("truth prevalence calibration",abs(sum(cal$p*cal$q)-cal$pi)<1e-10)
check("PIT bounds normalize",all(vapply(cal$bounds,function(b) all(b$lo>=0 & b$hi<=1+1e-10 & b$hi>=b$lo),logical(1))))
d<-draw_scores(200000,cal,s)
aa<-both_auc(d$a,d$ref,d$y);bb<-both_auc(d$b,d$ref,d$y)
check("specified binormal true AUC recovered",max(abs(c(aa[2],bb[2])-.85))<.004)
check("truth-conditional score mean",max(abs(tapply(d$a-sqrt(2)*qnorm(.85)*d$y,d$y,mean)))<.02)
check("truth-conditional score variance",max(abs(tapply(d$a,d$y,var)-1))<.025)
k<-d$keep;fa<-both_auc(d$a[k],d$ref[k],d$y[k]);fb<-both_auc(d$b[k],d$ref[k],d$y[k])
check("identical retained-reference AUC",fa[1]==both_auc(d$a[k],pattern_votes$common[d$ix][k],d$y[k])[1])
check("bias decomposition",abs((fa[1]-.85)-((fa[1]-fa[2])+(fa[2]-.85)))<1e-12)
s$inheritance<-0;direction<-replicate(300,{
  z<-simulation_rep(2000,cal,s);ordering(z["full_a_ref"]-z["full_b_ref"])
})
check("zero inheritance equal-AUC selection symmetry",abs(mean(direction))<.2)
dir.create(out_dir,recursive=TRUE,showWarnings=FALSE)
fwrite(rbindlist(checks),file.path(out_dir,"software-checks.csv"))
write_run("software-checks-run.json",started,list(synthetic_seed=814,checks=length(checks),passed=TRUE,
  synthetic_auc_a=unname(aa[2]),synthetic_auc_b=unname(bb[2]),zero_inheritance_preference=mean(direction)))
message(length(checks)," statistical software checks passed.")
